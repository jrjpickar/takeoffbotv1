import {readFileSync} from 'node:fs';
import {test,expect} from '@playwright/test';

const fixture=process.env.A2Z_PINE_ZIP;
test.skip(!fixture,'Set A2Z_PINE_ZIP to the private Pine Street ZIP.');
test('Pine ZIP imports and produces wall candidates',async({page})=>{
  test.setTimeout(120000);
  await page.goto('/');
  await page.getByLabel('Passcode').fill('local-browser-test-only');
  await page.getByRole('button',{name:'Unlock'}).click();
  await expect(page.getByRole('button',{name:'Open sample'})).toBeEnabled();
  await page.getByTestId('upload').setInputFiles(fixture!);
  await expect(page.getByRole('navigation',{name:'Sheets'}).getByRole('button')).toHaveCount(44,{timeout:60000});
  await page.getByRole('button',{name:/^A-1\.01\b/}).click();
  await expect(page.getByTestId('paper')).toHaveAttribute('data-ready','true',{timeout:30000});
  await page.getByRole('button',{name:'Calibrate',exact:true}).click();
  const paper=await page.getByTestId('paper').boundingBox();
  if(!paper)throw new Error('Missing plan canvas');
  const pos=(x:number,y:number)=>[paper.x+x/2592*paper.width,paper.y+y/2592*paper.width] as const;
  await page.mouse.click(...pos(1491,720));
  await page.mouse.click(...pos(1695,720));
  await page.getByLabel('Known distance (ft)').fill('15.111111');
  await page.getByRole('button',{name:'Apply scale'}).click();
  await page.getByRole('button',{name:'Run sheet takeoff'}).click();
  await expect(page.getByRole('status')).toHaveText(/^[1-9]\d* added for review/,{timeout:60000});
  console.log(await page.getByRole('status').innerText(),await page.getByText(/Sheet warnings/).innerText());
  await page.getByText(/Sheet warnings/).click();
  console.log(await page.locator('.warnings').innerText());
  const rows=page.locator('.measurements button');
  await expect(rows).toHaveCount(26);
  await page.getByRole('button',{name:'Run sheet takeoff'}).click();
  await expect(page.getByRole('status')).toHaveText('0 added for review, 26 already present.');
  await expect(rows.first()).toContainText('LF');
  await page.getByLabel('Interior walls takeoff color').fill('#0055ff');
  await expect(rows.first().locator('i')).toHaveCSS('background-color','rgb(0, 85, 255)');
  page.once('dialog',d=>d.accept());
  await page.getByRole('button',{name:'Clear sheet takeoffs'}).click();
  await expect(rows).toHaveCount(0);
  await expect(page.locator('.scale-status')).toContainText('calibration');
  await page.getByRole('button',{name:'Undo',exact:true}).click();
  await expect(rows).toHaveCount(26);
  await page.getByRole('button',{name:'Save',exact:true}).click();
  await expect(page.getByRole('status')).toHaveText('Saved revision 1.');
  await page.reload();
  await page.getByRole('combobox',{name:'Open saved project'}).selectOption({label:'10932_PINE_ST_LOS_ALAMITOSV08082026V01_1.pdf'});
  await page.getByRole('button',{name:/^A-1\.01\b/}).click();
  await expect(rows.first().locator('i')).toHaveCSS('background-color','rgb(0, 85, 255)');
  const viewer=page.getByTestId('viewer');
  await viewer.hover();
  await page.mouse.wheel(0,-160);
  await expect(page.getByRole('button',{name:'149%'})).toBeVisible();
  await page.mouse.wheel(0,-160);
  const view=await viewer.boundingBox();
  if(!view)throw new Error('Missing viewer');
  await page.locator('body').focus();
  const before=await viewer.evaluate(el=>el.scrollLeft);
  await page.keyboard.down('Space');
  await page.mouse.move(view.x+view.width/2,view.y+view.height/2);
  await page.mouse.down();await page.mouse.move(view.x+view.width/2-70,view.y+view.height/2,{steps:5});
  await page.mouse.up();await page.keyboard.up('Space');
  expect(await viewer.evaluate(el=>el.scrollLeft)).toBeGreaterThan(before);
  await page.mouse.wheel(0,160);
  await expect(page.getByRole('button',{name:'149%'})).toBeVisible();
});

test('Pine ceiling hatch and switching scopes',async({page})=>{
  test.setTimeout(90000);
  await page.goto('/');
  await page.getByLabel('Passcode').fill('local-browser-test-only');
  await page.getByRole('button',{name:'Unlock'}).click();
  await expect(page.getByRole('button',{name:'Open sample'})).toBeEnabled();
  await page.getByTestId('upload').setInputFiles(fixture!);
  const filter=page.getByLabel('Filter sheets');
  await filter.selectOption('demo');
  await expect(page.getByRole('navigation',{name:'Sheets'}).getByRole('button')).toHaveCount(2);
  await expect(page.getByRole('button',{name:/^A-1\.01\b/})).toHaveClass(/demo-sheet/);
  await filter.selectOption('ceiling');
  await page.getByRole('button',{name:/^A-1\.04\b/}).click();
  await expect(page.getByTestId('paper')).toHaveAttribute('data-ready','true',{timeout:30000});
  await page.getByRole('button',{name:'Run all sheets'}).click();
  await expect(page.getByRole('status')).toHaveText('Scanned 44 sheets: 2 matched, 32 added for review, 0 already present.',{timeout:60000});
  const rows=page.locator('.measurements button');
  await expect(rows).toHaveCount(6);
  await expect(rows.first()).toContainText('Ceilings');
  await expect(page.locator('.scale-status')).toContainText('Printed scale: 3/16');
  for(const row of await rows.all())await expect(row).toContainText(/\d+(?:\.\d+)? SF/);
  const exported=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export all takeoffs'}).click();
  const csv=readFileSync((await (await exported).path())!,'utf8');
  expect(csv.trim().split(/\r?\n/)).toHaveLength(33);
  expect(csv).toContain('A-1.01 - DEMOLITION PLAN,10,Interior walls,In review');
  expect(csv).toContain('A-1.04 - EXISTING REFLECTED CEILING PLAN,13,Ceilings,In review');

  await page.getByRole('button',{name:'Ceilings SF',exact:true}).click();
  await expect(page.getByRole('button',{name:'Polygon',exact:true})).toHaveAttribute('aria-pressed','true');
  await page.getByRole('button',{name:'Doors EA',exact:true}).click();
  await expect(page.getByRole('button',{name:'Count',exact:true})).toHaveAttribute('aria-pressed','true');
  await page.getByRole('button',{name:'Interior walls LF',exact:true}).click();
  await expect(page.getByRole('button',{name:'Line',exact:true})).toHaveAttribute('aria-pressed','true');
});
